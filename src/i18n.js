function detect() {
  let saved = null
  try {
    saved = localStorage.getItem(STORAGE_KEY)
  } catch {
    // приватный режим — просто игнорируем хранилище
  }
  if (saved && messages[saved]) return saved
  const nav = (navigator.language || '').toLowerCase()
  // Казахский — родной язык продукта, поэтому он же и для kk-локали браузера.
  return nav.startsWith('kk') ? 'kk' : 'ru'
}

export const locale = ref(detect())

// Достаём значение по пути вида 'hero.sub'. Если ключа нет — возвращаем сам
// путь, чтобы пропажа строки была видна, а не превращалась в пустоту.
export function t(path) {
  const dict = messages[locale.value] || messages.ru
  const val = path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict)
  return val === undefined ? path : val
}

export function applyDocumentLocale() {
  document.documentElement.lang = locale.value
  document.title = t('meta.title')
  const desc = document.querySelector('meta[name="description"]')
  if (desc) desc.setAttribute('content', t('meta.description'))
}

export function setLocale(code) {
  if (!messages[code]) return
  locale.value = code
  try {
    localStorage.setItem(STORAGE_KEY, code)
  } catch {
    // не критично, просто не запомним выбор
  }
  applyDocumentLocale()
}
